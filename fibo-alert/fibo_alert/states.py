WAITING, WATCHING = "WAITING", "WATCHING"
BREAKOUT_CONFIRMED, RETEST_PENDING = "BREAKOUT_CONFIRMED", "RETEST_PENDING"
ENTRY_CANDIDATE, TARGET_REACHED, TRAILING, CLOSED = "ENTRY_CANDIDATE", "TARGET_REACHED", "TRAILING", "CLOSED"
INVALIDATED, TIMEOUT, DATA_ERROR = "INVALIDATED", "TIMEOUT", "DATA_ERROR"

TERMINAL = {CLOSED, INVALIDATED, TIMEOUT}
POSITION_STATES = {ENTRY_CANDIDATE, TARGET_REACHED, TRAILING}
PRE_ENTRY = {WAITING, WATCHING, BREAKOUT_CONFIRMED, RETEST_PENDING}

# 패턴 A 는 BREAKOUT_CONFIRMED 를 거치지 않고 WATCHING → RETEST_PENDING(더블탑 형성, 넥라인 이탈 대기).
# DATA_ERROR 는 신호가 아니라 엔진 단위로 관리한다(meta 'engine_status'): 데이터가 틀리면
# 그 봉을 처리하지 않고 멈춘 채 재시도하므로 신호 상태를 추측으로 바꾸지 않는다.
ALLOWED = {
    WAITING: {WATCHING, INVALIDATED, TIMEOUT},
    WATCHING: {BREAKOUT_CONFIRMED, RETEST_PENDING, INVALIDATED, TIMEOUT},
    BREAKOUT_CONFIRMED: {RETEST_PENDING, WATCHING, INVALIDATED, TIMEOUT},
    RETEST_PENDING: {ENTRY_CANDIDATE, INVALIDATED, TIMEOUT},
    ENTRY_CANDIDATE: {TARGET_REACHED, CLOSED},
    TARGET_REACHED: {TRAILING, CLOSED},
    TRAILING: {CLOSED},
    CLOSED: set(), INVALIDATED: set(), TIMEOUT: set(),
}


def check_transition(frm: str, to: str):
    if to not in ALLOWED.get(frm, set()):
        raise ValueError(f"illegal transition {frm} -> {to}")
